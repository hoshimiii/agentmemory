MANIFEST_TEMPLATE = {
    "schema_version": 1,
    "local_records": ".continuity/local",
    "project_records": ".continuity/shared/records",
    "derived_summary": ".continuity/CONTINUITY.md",
}

CONTINUITY_PLACEHOLDER = "# AgentMemory continuity scaffold\n\nDo not edit this file manually.\n"


class StorageError(RuntimeError):
    """Raised when checkpoint layout or persistence fails."""


class StorageConflictError(StorageError):
    """Raised when a checkpoint conflicts with an immutable existing record."""


class StoragePathError(StorageError):
    """Raised when a persistence path is unsafe."""


def _timestamp_utc() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def _lstat(path: Path) -> Optional[os.stat_result]:
    try:
        return os.lstat(path)
    except FileNotFoundError:
        return None


def _validate_within_root(root: Path, target: Path, *, target_is_file: bool) -> None:
    root_abs = root.absolute()
    root_info = _lstat(root_abs)
    if root_info is not None:
        root_mode = stat.S_IFMT(root_info.st_mode)
        if stat.S_ISLNK(root_mode) or not stat.S_ISDIR(root_mode):
            raise StoragePathError("path target is invalid")

    target_abs = target.absolute()
    try:
        if os.path.commonpath([str(root_abs), str(target_abs)]) != str(root_abs):
            raise StoragePathError("path escapes repository root")
    except ValueError as exc:
        raise StoragePathError("path escapes repository root") from exc

    rel = target_abs.relative_to(root_abs)
    cursor = root_abs
    for index, part in enumerate(rel.parts):
        cursor = cursor / part
        info = _lstat(cursor)
        if info is None:
            continue

        mode = stat.S_IFMT(info.st_mode)
        if stat.S_ISLNK(mode):
            raise StoragePathError("path contains symbolic link")

        if stat.S_ISDIR(mode):
            continue

        if stat.S_ISREG(mode) and target_is_file and index == len(rel.parts) - 1:
            continue

        if stat.S_ISREG(mode) and not target_is_file:
            raise StoragePathError("path contains regular file where directory is required")

        raise StoragePathError("path contains unsupported file type")


def _load_identity(repo_path: Optional[Union[str, Path]]) -> Dict[str, str]:
    try:
        return get_git_identity(repo_path)
    except GitIdentityError as exc:
        raise StorageError(GIT_IDENTITY_ERROR) from exc


def _compatible_manifest(path: Path) -> bool:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return False
    return isinstance(value, dict) and value == MANIFEST_TEMPLATE


def _compatible_continuity(path: Path) -> bool:
    try:
        text = path.read_text(encoding="utf-8")
    except Exception:
        return False
    return text == CONTINUITY_PLACEHOLDER or text.startswith(CONTINUITY_GENERATED_HEADER)


def _compute_project_record_id(candidate: Dict[str, Any]) -> str:
    payload = b"agentmemory/project-record/v1\0" + candidate["integrity"]["content_hash"].encode("ascii")
    return hashlib.sha256(payload).hexdigest()


def _validate_json_object(payload: Any) -> Dict[str, Any]:
    if not isinstance(payload, dict):
        raise RecordValidationError("record must be an object")
    return payload


def _validate_record_file(path: Path, *, label: str) -> Dict[str, Any]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError) as exc:
        raise StorageError(f"malformed {label} payload") from exc
    except json.JSONDecodeError as exc:
        raise StorageError(f"malformed {label} payload") from exc
    payload = _validate_json_object(payload)
    return validate_record(payload)


def _candidate_payload(path: Path) -> Dict[str, Any]:
    payload = _validate_record_file(path, label="candidate")
    validated = validate_record(payload)
    if validated["record_type"] != "candidate":
        raise StorageError("candidate record type mismatch")
    return validated

def _gitignore_has_exact_ignore_line(repo_root: Path) -> bool:
    path = repo_root / ".gitignore"
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except FileNotFoundError:
        return False
    except OSError:
        raise
    return LOCAL_IGNORE_LINE in lines


def _resolve_layout(identity: Dict[str, str]) -> Dict[str, Path]:
    repo_root = Path(identity["toplevel"])
    continuity = repo_root / ".continuity"
    local = continuity / "local"
    checkpoints = local / "worktrees" / identity["worktree_id"] / "checkpoints"
    return {
        "repo_root": repo_root,
        "continuity": continuity,
        "manifest": continuity / "manifest.json",
        "continuity_md": continuity / "CONTINUITY.md",
        "local": local,
        "candidate_dir": local / "worktrees" / identity["worktree_id"] / "candidates",
        "shared_records": continuity / "shared" / "records",
        "project_records": continuity / "shared" / "records",
        "lock": local / "locks" / "write.lock",
        "checkpoint_dir": checkpoints,
    }


def _fsync_parent_dir(path: Path) -> None:
    flags = getattr(os, "O_DIRECTORY", os.O_RDONLY)
    descriptor: Optional[int] = None
    try:
        descriptor = os.open(str(path), flags)
        os.fsync(descriptor)
    except OSError:
        pass
    finally:
        if descriptor is not None:
            try:
                os.close(descriptor)
            except OSError:
                pass


def _atomic_write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(
        dir=str(path.parent),
        prefix=f".{path.name}.",
        suffix=".tmp",
    )
    tmp_path = Path(tmp_name)
    wrote = False
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(str(tmp_path), str(path))
        wrote = True
        _fsync_parent_dir(path.parent)
    finally:
        if not wrote and tmp_path.exists():
            try:
                tmp_path.unlink()
            except OSError:
                pass


def _stable_record_fingerprint(record: Dict[str, Any]) -> str:
    stable = dict(record)
    stable.pop("created_at", None)
    stable.pop("integrity", None)
    return canonical_json_dumps(stable)


def _validate_path_set(layout: Dict[str, Path], repo_root: Path) -> None:
    _validate_within_root(repo_root, layout["manifest"], target_is_file=True)
    _validate_within_root(repo_root, layout["continuity_md"], target_is_file=True)
    _validate_within_root(repo_root, repo_root / ".gitignore", target_is_file=True)
    _validate_within_root(repo_root, layout["shared_records"], target_is_file=False)
    _validate_within_root(repo_root, layout["candidate_dir"], target_is_file=False)
    _validate_within_root(repo_root, layout["checkpoint_dir"], target_is_file=False)
    _validate_within_root(repo_root, layout["lock"], target_is_file=True)


def _is_initialized_layout(layout: Dict[str, Path], repo_root: Path, *, require_gitignore: bool) -> bool:
    _validate_path_set(layout, repo_root)
    if not layout["manifest"].exists():
        return False
    if not layout["continuity_md"].exists():
        return False
    if not _compatible_manifest(layout["manifest"]):
        return False
    if not _compatible_continuity(layout["continuity_md"]):
        return False
    if require_gitignore and not _gitignore_has_exact_ignore_line(repo_root):
        return False
    return True


def _ensure_initialized_for_checkpoint(layout: Dict[str, Path], repo_root: Path) -> None:
    if not _is_initialized_layout(layout, repo_root, require_gitignore=True):
        raise StorageError("repository is not initialized")


def _ensure_initialized_for_projects(layout: Dict[str, Path], repo_root: Path) -> None:
    _validate_path_set(layout, repo_root)
    if not layout["manifest"].exists():
        raise StorageError("repository is not initialized")
    if not _compatible_manifest(layout["manifest"]):
        raise StorageError("repository is not initialized")
    if layout["continuity_md"].exists() and not _compatible_continuity(layout["continuity_md"]):
        raise StorageError("incompatible continuity marker")
    if not _gitignore_has_exact_ignore_line(repo_root):
        raise StorageError("repository is not initialized")


def _generate_record_id() -> str:
    token = secrets.token_hex(16)
    return "cp-" + token


def _generate_candidate_id() -> str:
    return "cand-" + secrets.token_hex(16)


def _normalize_record_id(record_id: Optional[str]) -> str:
    if record_id is None:
        return _generate_record_id()
    return record_id


