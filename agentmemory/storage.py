def _read_checkpoint_record(path: Path) -> Dict[str, Any]:
    return _validate_record_file(path, label="checkpoint")


def _read_project_record(path: Path) -> Dict[str, Any]:
    return _validate_record_file(path, label="project")


def _checkpoint_stable_match(path: Path, expected: Dict[str, Any]) -> bool:
    payload = _read_checkpoint_record(path)
    return _stable_record_fingerprint(payload) == _stable_record_fingerprint(expected)


def _ensure_checkpoint_idempotent(path: Path, expected: Dict[str, Any]) -> bool:
    if not path.exists():
        return False
    try:
        if _checkpoint_stable_match(path, expected):
            return True
        raise StorageConflictError("checkpoint id already exists with conflicting content")
    except (RecordValidationError, StorageError) as exc:
        raise StorageConflictError("checkpoint id already exists with invalid content") from exc


def _ensure_candidate_idempotent(path: Path, expected: Dict[str, Any]) -> bool:
    if not path.exists():
        return False
    try:
        payload = _read_checkpoint_record(path)
    except (RecordValidationError, StorageError) as exc:
        raise StorageConflictError("candidate id already exists with invalid content") from exc
    if _stable_record_fingerprint(payload) == _stable_record_fingerprint(expected):
        return True
    raise StorageConflictError("candidate id already exists with conflicting content")

def _validate_candidate_id(candidate_id: Any) -> str:
    if not isinstance(candidate_id, str):
        raise StorageError("invalid candidate id")
    if len(candidate_id) > MAX_RECORD_ID_LENGTH:
        raise StorageError("invalid candidate id")
    if RECORD_ID_RE.match(candidate_id) is None:
        raise StorageError("invalid candidate id")
    return candidate_id


def _validate_candidate_file(candidate_path: Path, candidate_id: str) -> Dict[str, Any]:
    if candidate_path.stem != candidate_id:
        raise StorageError("candidate filename mismatch")
    if not candidate_path.exists():
        raise StorageError("candidate record is missing")
    info = _lstat(candidate_path)
    if info is None:
        raise StorageError("candidate record is missing")
    mode = stat.S_IFMT(info.st_mode)
    if stat.S_ISLNK(mode) or not stat.S_ISREG(mode):
        raise StorageError("candidate record must be a regular file")
    payload = _candidate_payload(candidate_path)
    if payload["id"] != candidate_id:
        raise StorageError("candidate filename mismatch")
    return payload


def _iter_project_records(repo_root: Path, shared_records: Path) -> List[Dict[str, Any]]:
    records: List[Dict[str, Any]] = []
    for path in sorted(shared_records.iterdir(), key=lambda item: item.name):
        _validate_within_root(repo_root, path, target_is_file=True)
        info = _lstat(path)
        if info is None:
            continue
        mode = stat.S_IFMT(info.st_mode)
        if stat.S_ISLNK(mode):
            raise StorageError("shared records must not contain symlinks")
        if not stat.S_ISREG(mode):
            raise StorageError("shared records contains invalid entry type")
        if path.suffix != ".json":
            raise StorageError("shared records must contain JSON files only")
        try:
            validated = _read_project_record(path)
        except (RecordValidationError, StorageError) as exc:
            raise StorageError("malformed shared project record") from exc
        if validated["id"] != path.stem:
            raise StorageError("shared record filename mismatch")
        if validated["schema_version"] != 1:
            raise StorageError("v2 experience is not a v1 shared record")
        records.append(validated)
    return records


def _read_experience_record(path: Path) -> Dict[str, Any]:
    record = _validate_record_file(path, label="experience")
    if record["schema_version"] != 2 or record["record_type"] != "project_record":
        raise StorageError("experience record type mismatch")
    return record


def _iter_experience_records(repo_root: Path, directory: Path) -> List[Dict[str, Any]]:
    if not directory.exists():
        return []
    records: List[Dict[str, Any]] = []
    for path in sorted(directory.iterdir(), key=lambda item: item.name):
        _validate_within_root(repo_root, path, target_is_file=True)
        info = _lstat(path)
        if info is None:
            continue
        mode = stat.S_IFMT(info.st_mode)
        if stat.S_ISLNK(mode) or not stat.S_ISREG(mode) or path.suffix != ".json":
            raise StorageError("experience sidecar contains invalid entry")
        try:
            record = _read_experience_record(path)
        except (RecordValidationError, StorageError) as exc:
            raise StorageError("malformed experience sidecar") from exc
        if record["id"] != path.stem:
            raise StorageError("experience filename mismatch")
        records.append(record)
    return records


def _experience_visible(record: Dict[str, Any], identity: Dict[str, str]) -> bool:
    applies = record["applies_to"]
    if applies["repository_id"] != identity["repository_id"]:
        raise StorageError("experience repository mismatch")
    if identity["branch"] == "DETACHED":
        return applies["branch"] == "DETACHED" and applies["head"] == identity["head"]
    return applies["branch"] == identity["branch"]


def _validate_experience_graph(records: List[Dict[str, Any]]) -> None:
    ids = {record["id"] for record in records}
    graph: Dict[str, List[str]] = {record["id"]: [] for record in records}
    for record in records:
        experience = record["experience"]
        refs = [*experience["lineage"]["supersedes"], *experience["lineage"]["deprecates"]]
        strategy_id = experience["relation"]["strategy_id"]
        if strategy_id is not None:
            refs.append(strategy_id)
        if any(reference not in ids for reference in refs):
            raise StorageError("experience graph references an unknown record")
        graph[record["id"]].extend(refs)
    visiting, visited = set(), set()
    def visit(record_id: str) -> None:
        if record_id in visiting:
            raise StorageError("experience graph contains a cycle")
        if record_id not in visited:
            visiting.add(record_id)
            for target in graph[record_id]:
                visit(target)
            visiting.remove(record_id)
            visited.add(record_id)
    for record_id in sorted(graph):
        visit(record_id)


def _experience_lifecycle(records: List[Dict[str, Any]]) -> Dict[str, str]:
    _validate_experience_graph(records)
    state = {record["id"]: "active" for record in records}
    for record in records:
        for target in record["experience"]["lineage"]["supersedes"]:
            state[target] = "superseded"
    for record in records:
        for target in record["experience"]["lineage"]["deprecates"]:
            state[target] = "deprecated"
    return state


def _load_trusted_experiences(identity: Dict[str, str], directory: Path, receipt_dir: Path, repo_root: Path) -> List[Dict[str, Any]]:
    records = _iter_experience_records(repo_root, directory)
    for record in records:
        if record["created_at"] != record["review"]["confirmed_at"]:
            raise StorageError("experience confirmation timestamp mismatch")
    records = [record for record in records if _experience_visible(record, identity)]
    receipts = _iter_review_receipts(repo_root, receipt_dir, identity)
    trusted: List[Dict[str, Any]] = []
    for record in records:
        receipt = receipts.get(record["id"])
        if receipt is None:
            continue
        if receipt["content_hash"] != record["integrity"]["content_hash"]:
            raise StorageError("conflicting experience review receipt")
        trusted.append(record)
    # References to a missing receipt are not trusted targets and fail review/load closed.
    trusted_ids = {record["id"] for record in trusted}
    for record in trusted:
        refs = [*record["experience"]["lineage"]["supersedes"], *record["experience"]["lineage"]["deprecates"]]
        strategy_id = record["experience"]["relation"]["strategy_id"]
        if strategy_id is not None:
            refs.append(strategy_id)
        if any(reference not in trusted_ids for reference in refs):
            raise StorageError("experience references an untrusted record")
    lifecycle = _experience_lifecycle(trusted)
    active_warning_counts: Dict[str, int] = {}
    by_id = {record["id"]: record for record in trusted}
    for record in trusted:
        strategy_id = record["experience"]["relation"]["strategy_id"]
        if strategy_id is not None and by_id[strategy_id]["kind"] != "strategy":
            raise StorageError("warning has invalid strategy relation")
        if (
            record["kind"] != "warning"
            or strategy_id is None
            or lifecycle[record["id"]] != "active"
            or lifecycle[strategy_id] != "active"
        ):
            continue
        active_warning_counts[strategy_id] = active_warning_counts.get(strategy_id, 0) + 1
        if active_warning_counts[strategy_id] > 8:
            raise StorageError("strategy has too many active warnings")
    return [dict(record, lifecycle=lifecycle[record["id"]]) for record in sorted(trusted, key=lambda item: item["id"])]


def load_trusted_experiences(repo_path: Optional[Union[str, Path]] = None) -> List[Dict[str, Any]]:
    """Return receipt-gated, current-identity v2 records with derived lifecycle."""
    identity = _load_identity(repo_path)
    layout = _resolve_layout(identity)
    repo_root = layout["repo_root"]
    _ensure_initialized_for_projects(layout, repo_root)
    _validate_within_root(repo_root, layout["shared_experiences"], target_is_file=False)
    _validate_within_root(repo_root, layout["receipt_dir"], target_is_file=False)
    return _load_trusted_experiences(identity, layout["shared_experiences"], layout["receipt_dir"], repo_root)


def _build_review_receipt(
    identity: Dict[str, str],
    record: Dict[str, Any],
) -> Dict[str, Any]:
    return {
        "schema_version": 1,
        "repository_id": identity["repository_id"],
        "worktree_id": identity["worktree_id"],
        "record_id": record["id"],
        "content_hash": record["integrity"]["content_hash"],
    }


def _iter_review_receipts(
    repo_root: Path,
    receipt_dir: Path,
    identity: Dict[str, str],
) -> Dict[str, Dict[str, Any]]:
    if not receipt_dir.exists():
        return {}

    receipts: Dict[str, Dict[str, Any]] = {}
    expected_keys = {
        "schema_version",
        "repository_id",
        "worktree_id",
        "record_id",
        "content_hash",
    }
    for path in sorted(receipt_dir.iterdir(), key=lambda item: item.name):
        _validate_within_root(repo_root, path, target_is_file=True)
        info = _lstat(path)
        if info is None:
            continue
        mode = stat.S_IFMT(info.st_mode)
        if stat.S_ISLNK(mode) or not stat.S_ISREG(mode) or path.suffix != ".json":
            raise StorageError("review receipt entry must be a JSON file")
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, json.JSONDecodeError) as exc:
            raise StorageError("malformed review receipt") from exc
        if not isinstance(payload, dict) or set(payload) != expected_keys:
            raise StorageError("malformed review receipt")
        record_id = payload["record_id"]
        content_hash = payload["content_hash"]
        if (
            payload["schema_version"] != 1
            or payload["repository_id"] != identity["repository_id"]
            or payload["worktree_id"] != identity["worktree_id"]
            or not isinstance(record_id, str)
            or record_id != path.stem
            or len(record_id) > MAX_RECORD_ID_LENGTH
            or RECORD_ID_RE.match(record_id) is None
            or not isinstance(content_hash, str)
            or not content_hash.startswith("sha256:")
            or len(content_hash) != 71
            or any(char not in "0123456789abcdef" for char in content_hash[7:])
        ):
            raise StorageError("conflicting review receipt")
        receipts[record_id] = payload
    return receipts


def _iter_resume_checkpoints(
    repo_root: Path,
    checkpoint_dir: Path,
    identity: Dict[str, str],
) -> List[Dict[str, Any]]:
    if not checkpoint_dir.exists():
        return []

    records: List[Dict[str, Any]] = []
    for path in checkpoint_dir.iterdir():
        _validate_within_root(repo_root, path, target_is_file=True)
        info = _lstat(path)
        if info is None:
            continue

        mode = stat.S_IFMT(info.st_mode)
        if stat.S_ISLNK(mode) or not stat.S_ISREG(mode):
            raise StorageError("checkpoint entry must be a regular file")
        if path.suffix != ".json":
            raise StorageError("checkpoint entries must use .json extension")

        try:
            validated = _read_checkpoint_record(path)
        except (RecordValidationError, StorageError) as exc:
            raise StorageError("malformed checkpoint payload") from exc

        if validated["id"] != path.stem:
            raise StorageError("checkpoint filename mismatch")
        if validated["record_type"] != "checkpoint":
            raise StorageError("checkpoint type mismatch")

        applies_to = validated["applies_to"]
        if (
            applies_to["repository_id"] != identity["repository_id"]
            or applies_to["worktree_id"] != identity["worktree_id"]
        ):
            raise StorageError("checkpoint repository/worktree mismatch")

        _parse_created_at(validated["created_at"])
        records.append(validated)

    return records


def load_resume_state(repo_path: Optional[Union[str, Path]] = None) -> Dict[str, Any]:
    identity = _load_identity(repo_path)
    layout = _resolve_layout(identity)
    repo_root = layout["repo_root"]
    manifest = layout["manifest"]
    checkpoint_dir = layout["checkpoint_dir"]
    shared_records = layout["shared_records"]
    receipt_dir = layout["receipt_dir"]
    gitignore = repo_root / ".gitignore"

    _validate_within_root(repo_root, manifest, target_is_file=True)
    _validate_within_root(repo_root, gitignore, target_is_file=True)
    _validate_within_root(repo_root, checkpoint_dir, target_is_file=False)
    _validate_within_root(repo_root, shared_records, target_is_file=False)
    _validate_within_root(repo_root, receipt_dir, target_is_file=False)

    if not manifest.exists():
        raise StorageError("repository is not initialized")
    if not _compatible_manifest(manifest):
        raise StorageError("repository is not initialized")
    if not _gitignore_has_exact_ignore_line(repo_root):
        raise StorageError("repository is not initialized")

    all_checkpoints = _iter_resume_checkpoints(repo_root, checkpoint_dir, identity)
    branch_checkpoints = [
        item
        for item in all_checkpoints
        if item["applies_to"]["branch"] == identity["branch"]
    ]
    if not branch_checkpoints:
        return {
            "branch": identity["branch"],
            "head": identity["head"],
            "checkpoint": None,
            "stale_head": False,
            "project_records": [],
        }

    latest_checkpoint = max(
        branch_checkpoints,
        key=lambda item: (_parse_created_at(item["created_at"]), item["id"]),
    )
    stale_head = latest_checkpoint["applies_to"]["head"] != identity["head"]
    checkpoint = None if stale_head else latest_checkpoint

    project_records = (
        _load_shared_records_for_resume(identity, shared_records, receipt_dir, repo_root)
        if (checkpoint is not None or stale_head)
        else []
    )

    return {
        "branch": identity["branch"],
        "head": identity["head"],
        "checkpoint": checkpoint,
        "stale_head": stale_head,
        "project_records": project_records,
    }


def _filter_project_records(
    records: List[Dict[str, Any]],
    identity: Dict[str, str],
) -> List[Dict[str, Any]]:
    branch = identity["branch"]
    head = identity["head"]
    if branch == "DETACHED":
        return [
            record
            for record in records
            if record["applies_to"]["branch"] == "DETACHED" and record["applies_to"]["head"] == head
        ]
    return [record for record in records if record["applies_to"]["branch"] == branch]


def _ensure_gitignore_line(repo_root: Path) -> None:
    path = repo_root / ".gitignore"
    text_bytes = path.read_bytes() if path.exists() else b""
    try:
        text = text_bytes.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise StorageError("invalid .gitignore encoding") from exc
    newline = "\r\n" if b"\r\n" in text_bytes else "\n"

    if not text:
        _atomic_write_text(path, f"{LOCAL_IGNORE_LINE}\n")
        return

    lines = text.splitlines()
    deduped: List[str] = []
    seen = False
    for line in lines:
        if line == LOCAL_IGNORE_LINE:
            if seen:
                continue
            seen = True
        deduped.append(line)

    if not seen:
        deduped.append(LOCAL_IGNORE_LINE)

    reconstructed = newline.join(deduped)
    if text.endswith(("\r\n", "\n")):
        reconstructed += newline

    if reconstructed != text:
        _atomic_write_text(path, reconstructed)


def _parse_created_at(value: str) -> datetime:
    normalized = value[:-1] + "+00:00" if value.endswith("Z") else value
    parsed = datetime.fromisoformat(normalized)
    if parsed.tzinfo is None:
        raise ValueError("created_at has no timezone")
    return parsed


def _status_latest_checkpoint_id(
    repo_root: Path,
    identity: Dict[str, str],
    checkpoint_dir: Path,
) -> tuple[int, Optional[str]]:
    if not checkpoint_dir.exists():
        return 0, None

    validated: List[Tuple[datetime, str]] = []
    for path in checkpoint_dir.iterdir():
        _validate_within_root(repo_root, path, target_is_file=True)
        info = _lstat(path)
        if info is None:
            continue
        mode = stat.S_IFMT(info.st_mode)
        if not stat.S_ISREG(mode):
            raise StorageError("checkpoint directory contains non-regular file")
        if path.suffix != ".json":
            continue
        try:
            record = _read_checkpoint_record(path)
        except (RecordValidationError, StorageError) as exc:
            raise StorageError("malformed checkpoint payload") from exc
        if record["record_type"] != "checkpoint":
            raise StorageError("invalid checkpoint type")
        if record["id"] != path.stem:
            raise StorageError("checkpoint filename mismatch")
        applies = record["applies_to"]
        if (
            applies["repository_id"] != identity["repository_id"]
            or applies["worktree_id"] != identity["worktree_id"]
        ):
            raise StorageError("checkpoint repository mismatch")
        validated.append((_parse_created_at(record["created_at"]), path.stem))

    if not validated:
        return 0, None

    latest = max(validated, key=lambda item: (item[0], item[1]))
    return len(validated), latest[1]


def initialize_repository(repo_path: Optional[Union[str, Path]] = None) -> Dict[str, Any]:
    identity = _load_identity(repo_path)
    layout = _resolve_layout(identity)

    repo_root = layout["repo_root"]
    manifest = layout["manifest"]
    continuity_md = layout["continuity_md"]
    local = layout["local"]
    shared_records = layout["shared_records"]
    shared_experiences = layout["shared_experiences"]
    lock = layout["lock"]
    checkpoint_dir = layout["checkpoint_dir"]
    continuity = layout["continuity"]

    _validate_path_set(layout, repo_root)

    if manifest.exists() and not _compatible_manifest(manifest):
        raise StorageError("incompatible existing manifest")
    if continuity_md.exists() and not _compatible_continuity(continuity_md):
        raise StorageError("incompatible existing continuity marker")

    lock.parent.mkdir(parents=True, exist_ok=True)
    with FileLock(lock):
        _validate_path_set(layout, repo_root)
        if manifest.exists() and not _compatible_manifest(manifest):
            raise StorageError("incompatible existing manifest")
        if continuity_md.exists() and not _compatible_continuity(continuity_md):
            raise StorageError("incompatible existing continuity marker")

        try:
            continuity.mkdir(parents=True, exist_ok=True)
            local.mkdir(parents=True, exist_ok=True)
            shared_records.mkdir(parents=True, exist_ok=True)
            shared_experiences.mkdir(parents=True, exist_ok=True)
            checkpoint_dir.mkdir(parents=True, exist_ok=True)

            if not manifest.exists():
                _atomic_write_text(
                    manifest,
                    json.dumps(MANIFEST_TEMPLATE, indent=2, sort_keys=True),
                )
            if not continuity_md.exists():
                _atomic_write_text(continuity_md, CONTINUITY_PLACEHOLDER)

            _ensure_gitignore_line(repo_root)
        except (OSError, UnicodeError) as exc:
            raise StorageError("repository initialization failed") from exc

    return {
        "initialized": True,
        "repository_id": identity["repository_id"],
        "worktree_id": identity["worktree_id"],
        "branch": identity["branch"],
        "head": identity["head"],
    }


def create_checkpoint(
    repo_path: Optional[Union[str, Path]],
    summary: str,
    content: Dict[str, Any],
    paths: Optional[List[str]] = None,
    *,
    record_id: Optional[str] = None,
    ) -> Dict[str, Any]:
    if not isinstance(content, dict):
        raise StorageError("invalid content-json")

    identity = _load_identity(repo_path)
    layout = _resolve_layout(identity)
    repo_root = layout["repo_root"]
    lock = layout["lock"]
    checkpoint_dir = layout["checkpoint_dir"]

    prepared_id = _normalize_record_id(record_id)
    normalized_paths = list(paths or [])
    try:
        record = _build_record(
            identity,
            record_id=prepared_id,
            summary=summary,
            content=content,
            paths=normalized_paths,
        )
    except (RecordValidationError, SecretScanError) as exc:
        raise StorageError("invalid checkpoint payload") from exc

    if render_resume_capsule(
        {
            "branch": identity["branch"],
            "head": identity["head"],
            "stale_head": False,
            "checkpoint": record,
            "project_records": [],
        }
    ) is None:
        raise StorageError("checkpoint exceeds resume capsule budget")

    target = checkpoint_dir / f"{prepared_id}.json"

    _ensure_initialized_for_checkpoint(layout, repo_root)
    _validate_within_root(repo_root, target, target_is_file=True)

    with FileLock(lock):
        _validate_path_set(layout, repo_root)
        _validate_within_root(repo_root, target, target_is_file=True)

        if not _is_initialized_layout(layout, repo_root, require_gitignore=True):
            raise StorageError("repository is not initialized")

        if _ensure_checkpoint_idempotent(target, record):
            return {"id": prepared_id, "created": False}

        try:
            checkpoint_dir.mkdir(parents=True, exist_ok=True)
            _atomic_write_text(target, canonical_json_dumps(record))
        except Exception as exc:
            raise StorageError("checkpoint persistence failed") from exc

    return {"id": prepared_id, "created": True}


def create_candidate(
    repo_path: Optional[Union[str, Path]],
    kind: str,
    summary: str,
    content: Dict[str, Any],
    paths: Optional[List[str]] = None,
    *,
    semantic_role: str = "inference",
    record_id: Optional[str] = None,
    experience: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    if not isinstance(content, dict):
        raise StorageError("invalid content-json")

    identity = _load_identity(repo_path)
    layout = _resolve_layout(identity)
    repo_root = layout["repo_root"]
    lock = layout["lock"]
    candidate_dir = layout["candidate_dir"]
    candidate_id = _generate_candidate_id() if record_id is None else record_id

    try:
        if kind in ("strategy", "warning"):
            if not isinstance(experience, dict):
                raise StorageError("invalid experience payload")
            record = _build_experience_candidate_record(
                identity, candidate_id=candidate_id, kind=kind, semantic_role=semantic_role,
                summary=summary, content=content, paths=list(paths or []), experience=experience,
            )
        else:
            if experience is not None:
                raise StorageError("invalid experience payload")
            record = _build_candidate_record(
                identity, candidate_id=candidate_id, kind=kind, semantic_role=semantic_role,
                summary=summary, content=content, paths=list(paths or []),
            )
    except (RecordValidationError, SecretScanError) as exc:
        raise StorageError("invalid candidate payload") from exc

    target = candidate_dir / f"{candidate_id}.json"

    _ensure_initialized_for_checkpoint(layout, repo_root)
    _validate_within_root(repo_root, target, target_is_file=True)

    with FileLock(lock):
        _validate_path_set(layout, repo_root)
        _validate_within_root(repo_root, target, target_is_file=True)
        if not _is_initialized_layout(layout, repo_root, require_gitignore=True):
            raise StorageError("repository is not initialized")

        if _ensure_candidate_idempotent(target, record):
            return {"id": candidate_id, "created": False}

        try:
            candidate_dir.mkdir(parents=True, exist_ok=True)
            _atomic_write_text(target, canonical_json_dumps(record))
        except Exception as exc:
            raise StorageError("candidate persistence failed") from exc

    return {"id": candidate_id, "created": True}


def _validate_candidate_business_identity(candidate: Dict[str, Any], identity: Dict[str, str]) -> None:
    applies = candidate["applies_to"]
    if applies["repository_id"] != identity["repository_id"]:
        raise StorageError("candidate repository mismatch")
    if applies["worktree_id"] != identity["worktree_id"]:
        raise StorageError("candidate worktree mismatch")
    if applies["branch"] != identity["branch"] or applies["head"] != identity["head"]:
        raise StorageError("candidate checkout mismatch")


def _scan_source_candidate_conflict(
    records: List[Dict[str, Any]],
    candidate_id: str,
    repository_id: str,
    worktree_id: str,
    expected_project_id: str,
) -> None:
    for record in records:
        if record["provenance"]["source_record_id"] != candidate_id:
            continue
        applies_to = record["applies_to"]
        if (
            applies_to["repository_id"] == repository_id
            and applies_to["worktree_id"] == worktree_id
            and record["id"] != expected_project_id
        ):
            raise StorageConflictError("project record id conflicts with existing source candidate")


def _validate_experience_review(candidate: Dict[str, Any], identity: Dict[str, str], layout: Dict[str, Path], repo_root: Path) -> None:
    trusted = _load_trusted_experiences(identity, layout["shared_experiences"], layout["receipt_dir"], repo_root)
    trusted_records = [{key: value for key, value in record.items() if key != "lifecycle"} for record in trusted]
    by_id = {record["id"]: record for record in trusted_records}
    lifecycle = _experience_lifecycle(trusted_records)
    lineage = candidate["experience"]["lineage"]
    for target_id in lineage["supersedes"]:
        target = by_id.get(target_id)
        if target is None or target["kind"] != candidate["kind"] or lifecycle[target_id] != "active":
            raise StorageError("invalid experience supersession target")
        if any(target_id in record["experience"]["lineage"]["supersedes"] for record in trusted_records):
            raise StorageConflictError("experience supersession target already has a successor")
    for target_id in lineage["deprecates"]:
        if target_id not in by_id or lifecycle[target_id] not in ("active", "superseded"):
            raise StorageError("invalid experience deprecation target")
    strategy_id = candidate["experience"]["relation"]["strategy_id"]
    if strategy_id is not None:
        target = by_id.get(strategy_id)
        if target is None or target["kind"] != "strategy" or lifecycle[strategy_id] != "active":
            raise StorageError("invalid experience strategy target")
        warning_count = sum(
            record["kind"] == "warning" and record["experience"]["relation"]["strategy_id"] == strategy_id
            and lifecycle[record["id"]] == "active" for record in trusted_records
        )
        if warning_count >= 8:
            raise StorageConflictError("strategy already has eight active warnings")


def _review_experience_candidate(
    candidate: Dict[str, Any], candidate_id: str, identity: Dict[str, str], layout: Dict[str, Path], repo_root: Path,
) -> Dict[str, Any]:
    project_id = _compute_project_record_id(candidate)
    project_path = layout["shared_experiences"] / f"{project_id}.json"
    receipt_path = layout["receipt_dir"] / f"{project_id}.json"
    _validate_within_root(repo_root, project_path, target_is_file=True)
    _validate_within_root(repo_root, receipt_path, target_is_file=True)
    all_records = _iter_experience_records(repo_root, layout["shared_experiences"])
    _scan_source_candidate_conflict(all_records, candidate_id, identity["repository_id"], identity["worktree_id"], project_id)
    expected = _build_experience_project_record(candidate=candidate, project_id=project_id, timestamp=_timestamp_utc())
    if project_path.exists():
        existing = _read_experience_record(project_path)
        if existing["created_at"] != existing["review"]["confirmed_at"]:
            raise StorageError("experience confirmation timestamp mismatch")
        if _project_record_signature(existing) != _project_record_signature(expected):
            raise StorageConflictError("experience record already exists with conflicting content")
        trusted = _load_trusted_experiences(identity, layout["shared_experiences"], layout["receipt_dir"], repo_root)
        if any(record["id"] == project_id for record in trusted):
            return {"id": project_id, "created": False, "candidate_id": candidate_id}
        _validate_experience_review(candidate, identity, layout, repo_root)
        reviewed, result = existing, {"id": project_id, "created": False, "candidate_id": candidate_id}
    else:
        _validate_experience_review(candidate, identity, layout, repo_root)
        reviewed, result = expected, {"id": project_id, "created": True, "candidate_id": candidate_id}
    try:
        layout["receipt_dir"].mkdir(parents=True, exist_ok=True)
        _atomic_write_text(receipt_path, canonical_json_dumps(_build_review_receipt(identity, reviewed)))
    except Exception as exc:
        raise StorageError("review receipt persistence failed") from exc
    if result["created"]:
        try:
            layout["shared_experiences"].mkdir(parents=True, exist_ok=True)
            _atomic_write_text(project_path, canonical_json_dumps(reviewed))
        except Exception as exc:
            raise StorageError("experience persistence failed") from exc
    return result


def review_candidate(
    repo_path: Optional[Union[str, Path]],
    candidate_id: str,
) -> Dict[str, Any]:
    validated_candidate_id = _validate_candidate_id(candidate_id)
    identity = _load_identity(repo_path)
    layout = _resolve_layout(identity)
    repo_root = layout["repo_root"]
    lock = layout["lock"]
    candidate_path = layout["candidate_dir"] / f"{validated_candidate_id}.json"
    shared_records = layout["project_records"]
    receipt_dir = layout["receipt_dir"]
    continuity_md = layout["continuity_md"]

    _ensure_initialized_for_projects(layout, repo_root)
    _validate_within_root(repo_root, candidate_path, target_is_file=True)

    with FileLock(lock):
        _validate_path_set(layout, repo_root)
        _ensure_initialized_for_projects(layout, repo_root)
        identity = _load_identity(repo_root)

        _validate_within_root(repo_root, candidate_path, target_is_file=True)
        candidate = _validate_candidate_file(candidate_path, validated_candidate_id)
        _validate_candidate_business_identity(candidate, identity)

        if candidate["schema_version"] == 2:
            return _review_experience_candidate(candidate, validated_candidate_id, identity, layout, repo_root)

        project_id = _compute_project_record_id(candidate)
        project_path = shared_records / f"{project_id}.json"
        receipt_path = receipt_dir / f"{project_id}.json"
        _validate_within_root(repo_root, project_path, target_is_file=True)
        _validate_within_root(repo_root, receipt_path, target_is_file=True)

        existing_records = _load_validated_shared_records(identity, shared_records, repo_root) if shared_records.exists() else []
        _scan_source_candidate_conflict(
            existing_records,
            candidate_id=validated_candidate_id,
            repository_id=identity["repository_id"],
            worktree_id=identity["worktree_id"],
            expected_project_id=project_id,
        )

        timestamp = _timestamp_utc()
        expected = _build_project_record(
            candidate=candidate,
            project_id=project_id,
            timestamp=timestamp,
        )
        validated_project = validate_record(expected)

        if project_path.exists():
            existing = _read_project_record(project_path)
            if existing["created_at"] != existing["review"]["confirmed_at"]:
                raise StorageError("project record confirmation timestamp mismatch")
            if _project_record_signature(existing) == _project_record_signature(validated_project):
                reviewed_project = existing
                result = {"id": project_id, "created": False, "candidate_id": validated_candidate_id}
            else:
                raise StorageConflictError("project record already exists with conflicting content")
        else:
            reviewed_project = validated_project
            result = {"id": project_id, "created": True, "candidate_id": validated_candidate_id}

        try:
            receipt_dir.mkdir(parents=True, exist_ok=True)
            _atomic_write_text(
                receipt_path,
                canonical_json_dumps(_build_review_receipt(identity, reviewed_project)),
            )
        except Exception as exc:
            raise StorageError("review receipt persistence failed") from exc

        if result["created"]:
            try:
                shared_records.mkdir(parents=True, exist_ok=True)
                _atomic_write_text(project_path, canonical_json_dumps(validated_project))
            except Exception as exc:
                raise StorageError("project persistence failed") from exc
            existing_records = [*existing_records, validated_project]
        included = _filter_project_records(existing_records, identity)
        rendered = render_continuity_markdown(included, branch=identity["branch"])
        old_bytes = _read_continuity_bytes(continuity_md)
        if old_bytes != rendered.encode("utf-8"):
            _atomic_write_text(continuity_md, rendered)

    return result


def get_status(repo_path: Optional[Union[str, Path]]) -> Dict[str, Any]:
    identity = _load_identity(repo_path)
    layout = _resolve_layout(identity)
    repo_root = layout["repo_root"]

    _validate_path_set(layout, repo_root)

    initialized = _is_initialized_layout(layout, repo_root, require_gitignore=True)
    checkpoint_count, latest_checkpoint_id = (0, None)
    if initialized:
        checkpoint_count, latest_checkpoint_id = _status_latest_checkpoint_id(
            repo_root,
            identity,
            layout["checkpoint_dir"],
        )

    return {
        "initialized": initialized,
        "repository_id": identity["repository_id"],
        "worktree_id": identity["worktree_id"],
        "branch": identity["branch"],
        "head": identity["head"],
        "checkpoint_count": checkpoint_count,
        "latest_checkpoint_id": latest_checkpoint_id,
    }


def render_continuity(repo_path: Optional[Union[str, Path]]) -> Dict[str, Any]:
    identity = _load_identity(repo_path)
    layout = _resolve_layout(identity)
    repo_root = layout["repo_root"]
    lock = layout["lock"]
    continuity_md = layout["continuity_md"]

    _ensure_initialized_for_projects(layout, repo_root)

    with FileLock(lock):
        _validate_path_set(layout, repo_root)
        _ensure_initialized_for_projects(layout, repo_root)

        rendered_records = _load_shared_records_for_render(identity, layout["shared_records"], repo_root)
        rendered = render_continuity_markdown(rendered_records, branch=identity["branch"])
        try:
            existing = _read_continuity_bytes(continuity_md).decode("utf-8")
        except UnicodeDecodeError as exc:
            raise StorageError("cannot read continuity file") from exc

        if existing != rendered:
            _atomic_write_text(continuity_md, rendered)
            changed = True
        else:
            changed = False

    return {"count": len(rendered_records), "changed": changed}


def _load_validated_shared_records(
    identity: Dict[str, str],
    shared_records: Path,
    repo_root: Path,
) -> List[Dict[str, Any]]:
    records = _iter_project_records(repo_root, shared_records) if shared_records.exists() else []
    filtered: List[Dict[str, Any]] = []
    for record in records:
        if record["record_type"] != "project_record":
            raise StorageError("shared records must be project records")
        if record["scope"] != "project":
            raise StorageError("shared project records must have project scope")
        if record["status"] != "active":
            raise StorageError("shared project records must be active")
        if record["provenance"]["source"] != "explicit-review":
            raise StorageError("shared project records must have explicit-review provenance")
        if record["review"]["confirmed"] is not True:
            raise StorageError("shared project records must be explicitly confirmed")
        if record["review"]["confirmed_by"] != "explicit_user":
            raise StorageError("shared project records must be explicitly confirmed by user")
        if record["created_at"] != record["review"]["confirmed_at"]:
            raise StorageError("shared project records must have consistent confirmation timestamp")
        if record["applies_to"]["repository_id"] != identity["repository_id"]:
            raise StorageError("shared records contain records for another repository")
        filtered.append(record)
    return filtered


def _load_shared_records_for_render(
    identity: Dict[str, str],
    shared_records: Path,
    repo_root: Path,
) -> List[Dict[str, Any]]:
    return sorted(
        _filter_project_records(
            _load_validated_shared_records(identity, shared_records, repo_root),
            identity,
        ),
        key=lambda item: item["id"],
    )


def _load_shared_records_for_resume(
    identity: Dict[str, str],
    shared_records: Path,
    receipt_dir: Path,
    repo_root: Path,
) -> List[Dict[str, Any]]:
    records = _load_shared_records_for_render(identity, shared_records, repo_root)
    receipts = _iter_review_receipts(repo_root, receipt_dir, identity)
    return [
        record
        for record in records
        if (
            record["id"] in receipts
            and receipts[record["id"]]["content_hash"] == record["integrity"]["content_hash"]
        )
    ]


def _read_continuity_bytes(continuity_md: Path) -> bytes:
    if not continuity_md.exists():
        return b""
    try:
        return continuity_md.read_bytes()
    except OSError as exc:
        raise StorageError("cannot read continuity file") from exc


