"""Storage primitives for M2 local checkpoint persistence."""

from __future__ import annotations

import json
import os
import secrets
import stat
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple, Union

from .identity import GIT_IDENTITY_ERROR, GitIdentityError, get_git_identity
from .locking import FileLock
from .schema import (
    RecordValidationError,
    annotate_with_integrity,
    canonical_json_dumps,
    validate_record,
)
from .security import SecretScanError

LOCAL_IGNORE_LINE = ".continuity/local/"

MANIFEST_TEMPLATE = {
    "schema_version": 1,
    "local_records": ".continuity/local",
    "project_records": ".continuity/shared/records",
    "derived_summary": ".continuity/CONTINUITY.md",
}

CONTINUITY_PLACEHOLDER = "# AgentMemory continuity scaffold\n\nDo not edit this file manually.\n"


class StorageError(RuntimeError):
    """Raised when checkpoint layout or persistence fails."""


class StorageConflictError(StorageError):
    """Raised when a checkpoint conflicts with an immutable existing record."""


class StoragePathError(StorageError):
    """Raised when a persistence path is unsafe."""


def _timestamp_utc() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def _lstat(path: Path) -> Optional[os.stat_result]:
    try:
        return os.lstat(path)
    except FileNotFoundError:
        return None


def _validate_within_root(root: Path, target: Path, *, target_is_file: bool) -> None:
    root_abs = root.absolute()
    root_info = _lstat(root_abs)
    if root_info is not None:
        root_mode = stat.S_IFMT(root_info.st_mode)
        if stat.S_ISLNK(root_mode) or not stat.S_ISDIR(root_mode):
            raise StoragePathError("path target is invalid")

    target_abs = target.absolute()
    try:
        if os.path.commonpath([str(root_abs), str(target_abs)]) != str(root_abs):
            raise StoragePathError("path escapes repository root")
    except ValueError as exc:
        raise StoragePathError("path escapes repository root") from exc

    rel = target_abs.relative_to(root_abs)
    cursor = root_abs
    for index, part in enumerate(rel.parts):
        cursor = cursor / part
        info = _lstat(cursor)
        if info is None:
            continue

        mode = stat.S_IFMT(info.st_mode)
        if stat.S_ISLNK(mode):
            raise StoragePathError("path contains symbolic link")

        if stat.S_ISDIR(mode):
            continue

        if stat.S_ISREG(mode) and target_is_file and index == len(rel.parts) - 1:
            continue

        if stat.S_ISREG(mode) and not target_is_file:
            raise StoragePathError("path contains regular file where directory is required")

        raise StoragePathError("path contains unsupported file type")


def _load_identity(repo_path: Optional[Union[str, Path]]) -> Dict[str, str]:
    try:
        return get_git_identity(repo_path)
    except GitIdentityError as exc:
        raise StorageError(GIT_IDENTITY_ERROR) from exc


def _compatible_manifest(path: Path) -> bool:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return False
    return isinstance(value, dict) and value == MANIFEST_TEMPLATE


def _compatible_continuity(path: Path) -> bool:
    try:
        return path.read_text(encoding="utf-8") == CONTINUITY_PLACEHOLDER
    except Exception:
        return False


def _gitignore_has_exact_ignore_line(repo_root: Path) -> bool:
    path = repo_root / ".gitignore"
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except FileNotFoundError:
        return False
    except OSError:
        raise
    return LOCAL_IGNORE_LINE in lines


def _resolve_layout(identity: Dict[str, str]) -> Dict[str, Path]:
    repo_root = Path(identity["toplevel"])
    continuity = repo_root / ".continuity"
    local = continuity / "local"
    checkpoints = local / "worktrees" / identity["worktree_id"] / "checkpoints"
    return {
        "repo_root": repo_root,
        "continuity": continuity,
        "manifest": continuity / "manifest.json",
        "continuity_md": continuity / "CONTINUITY.md",
        "local": local,
        "shared_records": continuity / "shared" / "records",
        "lock": local / "locks" / "write.lock",
        "checkpoint_dir": checkpoints,
    }


def _fsync_parent_dir(path: Path) -> None:
    flags = getattr(os, "O_DIRECTORY", os.O_RDONLY)
    descriptor: Optional[int] = None
    try:
        descriptor = os.open(str(path), flags)
        os.fsync(descriptor)
    except OSError:
        pass
    finally:
        if descriptor is not None:
            try:
                os.close(descriptor)
            except OSError:
                pass


def _atomic_write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(
        dir=str(path.parent),
        prefix=f".{path.name}.",
        suffix=".tmp",
    )
    tmp_path = Path(tmp_name)
    wrote = False
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(str(tmp_path), str(path))
        wrote = True
        _fsync_parent_dir(path.parent)
    finally:
        if not wrote and tmp_path.exists():
            try:
                tmp_path.unlink()
            except OSError:
                pass


def _stable_record_fingerprint(record: Dict[str, Any]) -> str:
    stable = dict(record)
    stable.pop("created_at", None)
    stable.pop("integrity", None)
    return canonical_json_dumps(stable)


def _validate_path_set(layout: Dict[str, Path], repo_root: Path) -> None:
    _validate_within_root(repo_root, layout["manifest"], target_is_file=True)
    _validate_within_root(repo_root, layout["continuity_md"], target_is_file=True)
    _validate_within_root(repo_root, repo_root / ".gitignore", target_is_file=True)
    _validate_within_root(repo_root, layout["shared_records"], target_is_file=False)
    _validate_within_root(repo_root, layout["checkpoint_dir"], target_is_file=False)
    _validate_within_root(repo_root, layout["lock"], target_is_file=True)


def _is_initialized_layout(layout: Dict[str, Path], repo_root: Path, *, require_gitignore: bool) -> bool:
    _validate_path_set(layout, repo_root)
    if not layout["manifest"].exists():
        return False
    if not layout["continuity_md"].exists():
        return False
    if not _compatible_manifest(layout["manifest"]):
        return False
    if not _compatible_continuity(layout["continuity_md"]):
        return False
    if require_gitignore and not _gitignore_has_exact_ignore_line(repo_root):
        return False
    return True


def _ensure_initialized_for_checkpoint(layout: Dict[str, Path], repo_root: Path) -> None:
    if not _is_initialized_layout(layout, repo_root, require_gitignore=True):
        raise StorageError("repository is not initialized")


def _generate_record_id() -> str:
    token = secrets.token_hex(16)
    return "cp-" + token


def _normalize_record_id(record_id: Optional[str]) -> str:
    if record_id is None:
        return _generate_record_id()
    return record_id


def _build_record(
    identity: Dict[str, str],
    *,
    record_id: str,
    summary: str,
    content: Dict[str, Any],
    paths: List[str],
) -> Dict[str, Any]:
    record = {
        "schema_version": 1,
        "id": record_id,
        "record_type": "checkpoint",
        "kind": "checkpoint",
        "status": "active",
        "semantic_role": "fact",
        "summary": summary,
        "scope": "local",
        "applies_to": {
            "repository_id": identity["repository_id"],
            "worktree_id": identity["worktree_id"],
            "branch": identity["branch"],
            "head": identity["head"],
            "paths": list(paths),
        },
        "provenance": {
            "source": "cli",
            "evidence_refs": [],
            "source_record_id": record_id,
        },
        "content": content,
        "review": {
            "confirmed": False,
            "confirmed_by": None,
            "confirmed_at": None,
        },
        "created_at": _timestamp_utc(),
    }
    record = annotate_with_integrity(record, version=1)
    return validate_record(record)


def _read_checkpoint_record(path: Path) -> Dict[str, Any]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise RecordValidationError("record must be an object")
    return validate_record(payload)


def _checkpoint_stable_match(path: Path, expected: Dict[str, Any]) -> bool:
    payload = _read_checkpoint_record(path)
    return _stable_record_fingerprint(payload) == _stable_record_fingerprint(expected)


def _ensure_checkpoint_idempotent(path: Path, expected: Dict[str, Any]) -> bool:
    if not path.exists():
        return False
    try:
        if _checkpoint_stable_match(path, expected):
            return True
        raise StorageConflictError("checkpoint id already exists with conflicting content")
    except (RecordValidationError, json.JSONDecodeError, OSError) as exc:
        raise StorageConflictError("checkpoint id already exists with invalid content") from exc


def _ensure_gitignore_line(repo_root: Path) -> None:
    path = repo_root / ".gitignore"
    text_bytes = path.read_bytes() if path.exists() else b""
    try:
        text = text_bytes.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise StorageError("invalid .gitignore encoding") from exc
    newline = "\r\n" if b"\r\n" in text_bytes else "\n"

    if not text:
        _atomic_write_text(path, f"{LOCAL_IGNORE_LINE}\n")
        return

    lines = text.splitlines()
    deduped: List[str] = []
    seen = False
    for line in lines:
        if line == LOCAL_IGNORE_LINE:
            if seen:
                continue
            seen = True
        deduped.append(line)

    if not seen:
        deduped.append(LOCAL_IGNORE_LINE)

    reconstructed = newline.join(deduped)
    if text.endswith(("\r\n", "\n")):
        reconstructed += newline

    if reconstructed != text:
        _atomic_write_text(path, reconstructed)


def _parse_created_at(value: str) -> datetime:
    normalized = value[:-1] + "+00:00" if value.endswith("Z") else value
    parsed = datetime.fromisoformat(normalized)
    if parsed.tzinfo is None:
        raise ValueError("created_at has no timezone")
    return parsed


def _status_latest_checkpoint_id(
    repo_root: Path,
    identity: Dict[str, str],
    checkpoint_dir: Path,
) -> tuple[int, Optional[str]]:
    if not checkpoint_dir.exists():
        return 0, None

    validated: List[Tuple[datetime, str]] = []
    for path in checkpoint_dir.iterdir():
        _validate_within_root(repo_root, path, target_is_file=True)
        info = _lstat(path)
        if info is None:
            continue
        mode = stat.S_IFMT(info.st_mode)
        if not stat.S_ISREG(mode):
            raise StorageError("checkpoint directory contains non-regular file")
        if path.suffix != ".json":
            continue
        try:
            record = _read_checkpoint_record(path)
        except (RecordValidationError, json.JSONDecodeError, OSError) as exc:
            raise StorageError("malformed checkpoint payload") from exc
        if record["record_type"] != "checkpoint":
            raise StorageError("invalid checkpoint type")
        if record["id"] != path.stem:
            raise StorageError("checkpoint filename mismatch")
        applies = record["applies_to"]
        if (
            applies["repository_id"] != identity["repository_id"]
            or applies["worktree_id"] != identity["worktree_id"]
        ):
            raise StorageError("checkpoint repository mismatch")
        validated.append((_parse_created_at(record["created_at"]), path.stem))

    if not validated:
        return 0, None

    latest = max(validated, key=lambda item: (item[0], item[1]))
    return len(validated), latest[1]


def initialize_repository(repo_path: Optional[Union[str, Path]] = None) -> Dict[str, Any]:
    identity = _load_identity(repo_path)
    layout = _resolve_layout(identity)

    repo_root = layout["repo_root"]
    manifest = layout["manifest"]
    continuity_md = layout["continuity_md"]
    local = layout["local"]
    shared_records = layout["shared_records"]
    lock = layout["lock"]
    checkpoint_dir = layout["checkpoint_dir"]
    continuity = layout["continuity"]

    _validate_path_set(layout, repo_root)

    if manifest.exists() and not _compatible_manifest(manifest):
        raise StorageError("incompatible existing manifest")
    if continuity_md.exists() and not _compatible_continuity(continuity_md):
        raise StorageError("incompatible existing continuity marker")

    lock.parent.mkdir(parents=True, exist_ok=True)
    with FileLock(lock):
        _validate_path_set(layout, repo_root)
        if manifest.exists() and not _compatible_manifest(manifest):
            raise StorageError("incompatible existing manifest")
        if continuity_md.exists() and not _compatible_continuity(continuity_md):
            raise StorageError("incompatible existing continuity marker")

        try:
            continuity.mkdir(parents=True, exist_ok=True)
            local.mkdir(parents=True, exist_ok=True)
            shared_records.mkdir(parents=True, exist_ok=True)
            checkpoint_dir.mkdir(parents=True, exist_ok=True)

            if not manifest.exists():
                _atomic_write_text(
                    manifest,
                    json.dumps(MANIFEST_TEMPLATE, indent=2, sort_keys=True),
                )
            if not continuity_md.exists():
                _atomic_write_text(continuity_md, CONTINUITY_PLACEHOLDER)

            _ensure_gitignore_line(repo_root)
        except (OSError, UnicodeError) as exc:
            raise StorageError("repository initialization failed") from exc

    return {
        "initialized": True,
        "repository_id": identity["repository_id"],
        "worktree_id": identity["worktree_id"],
        "branch": identity["branch"],
        "head": identity["head"],
    }


def create_checkpoint(
    repo_path: Optional[Union[str, Path]],
    summary: str,
    content: Dict[str, Any],
    paths: Optional[List[str]] = None,
    *,
    record_id: Optional[str] = None,
) -> Dict[str, Any]:
    if not isinstance(content, dict):
        raise StorageError("content must be an object")

    identity = _load_identity(repo_path)
    layout = _resolve_layout(identity)
    repo_root = layout["repo_root"]
    lock = layout["lock"]
    checkpoint_dir = layout["checkpoint_dir"]

    prepared_id = _normalize_record_id(record_id)
    normalized_paths = list(paths or [])
    try:
        record = _build_record(
            identity,
            record_id=prepared_id,
            summary=summary,
            content=content,
            paths=normalized_paths,
        )
    except (RecordValidationError, SecretScanError) as exc:
        raise StorageError("invalid checkpoint payload") from exc

    target = checkpoint_dir / f"{prepared_id}.json"

    _ensure_initialized_for_checkpoint(layout, repo_root)
    _validate_within_root(repo_root, target, target_is_file=True)

    with FileLock(lock):
        _validate_path_set(layout, repo_root)
        _validate_within_root(repo_root, target, target_is_file=True)

        if not _is_initialized_layout(layout, repo_root, require_gitignore=True):
            raise StorageError("repository is not initialized")

        if _ensure_checkpoint_idempotent(target, record):
            return {"id": prepared_id, "created": False}

        try:
            checkpoint_dir.mkdir(parents=True, exist_ok=True)
            _atomic_write_text(target, canonical_json_dumps(record))
        except Exception as exc:
            raise StorageError("checkpoint persistence failed") from exc

    return {"id": prepared_id, "created": True}


def get_status(repo_path: Optional[Union[str, Path]]) -> Dict[str, Any]:
    identity = _load_identity(repo_path)
    layout = _resolve_layout(identity)
    repo_root = layout["repo_root"]

    _validate_path_set(layout, repo_root)

    initialized = _is_initialized_layout(layout, repo_root, require_gitignore=True)
    checkpoint_count, latest_checkpoint_id = (0, None)
    if initialized:
        checkpoint_count, latest_checkpoint_id = _status_latest_checkpoint_id(
            repo_root,
            identity,
            layout["checkpoint_dir"],
        )

    return {
        "initialized": initialized,
        "repository_id": identity["repository_id"],
        "worktree_id": identity["worktree_id"],
        "branch": identity["branch"],
        "head": identity["head"],
        "checkpoint_count": checkpoint_count,
        "latest_checkpoint_id": latest_checkpoint_id,
    }


